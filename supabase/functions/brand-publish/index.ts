// brand-publish: writes every active client brand (tenants.brand, saved in Brand Studio) to brands.js in
// the GitHub repo, which every page loads before brand.js. The commit goes to main, so Vercel deploys it.
// Called from brand-studio.html with the signed-in user's token; only the MarketPulse platform admin may.
// POST           publish (commits only if brands.js would change)
// POST ?check=1  report what would be published and whether GitHub is reachable; commits nothing
// Secrets: GIT_HUB_ACCESS (GitHub token with repo scope; also used by blog-dispatch).
import { createClient } from "npm:@supabase/supabase-js@2";

const SB_URL = Deno.env.get("SUPABASE_URL")!;
const admin = createClient(SB_URL, Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!, { auth: { persistSession: false } });
const REPO = Deno.env.get("BRAND_REPO") || "manish0solanki/indian_Stock_Market_news";
const BRANCH = "main";
const PATH = "brands.js";
const cors = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};
const json = (data: unknown, status = 200) => new Response(JSON.stringify(data), { status, headers: { ...cors, "Content-Type": "application/json" } });

// The file every page loads. Keep in step with the empty brands.js committed in the repo.
function render(brands: Record<string, unknown>) {
  return "/* Client brands for white-label sites, generated by Brand Studio (/brand-studio.html → brand-publish).\n" +
    "   Do not edit by hand: every publish rewrites this file from the database (tenants.brand).\n" +
    "   brand.js reads window.MP_BRANDS; a brand's hosts are the domains that show it. */\n" +
    "window.MP_BRANDS = " + JSON.stringify(brands, null, 2) + ";\n";
}
const b64 = (s: string) => { const bytes = new TextEncoder().encode(s); let bin = ""; for (const b of bytes) bin += String.fromCharCode(b); return btoa(bin); };
const unb64 = (s: string) => new TextDecoder().decode(Uint8Array.from(atob(s.replace(/\s/g, "")), (c) => c.charCodeAt(0)));

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: cors });
  if (req.method !== "POST") return json({ error: "POST only" }, 405);

  // The caller must be the platform admin: ask the database with their own token.
  const auth = req.headers.get("Authorization") || "";
  const anon = Deno.env.get("SUPABASE_ANON_KEY") || "";
  const who = await fetch(SB_URL + "/rest/v1/rpc/mp_is_platform_admin", { method: "POST", headers: { apikey: anon, Authorization: auth, "Content-Type": "application/json" }, body: "{}" });
  if (!who.ok || (await who.json()) !== true) return json({ error: "Only the MarketPulse admin can publish brands." }, 403);

  const { data: rows, error } = await admin.from("tenants").select("slug, hosts, brand").eq("active", true).not("brand", "is", null).order("slug");
  if (error) return json({ error: error.message }, 500);
  const brands: Record<string, unknown> = {};
  for (const r of rows || []) brands[r.slug] = { ...(r.brand as Record<string, unknown>), hosts: r.hosts || [] };
  const content = render(brands);

  const token = Deno.env.get("GIT_HUB_ACCESS");
  if (!token) return json({ error: "GIT_HUB_ACCESS secret is not set" }, 500);
  const gh = { Authorization: "Bearer " + token, Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "marketpulse-brand-studio", "Content-Type": "application/json" };
  const url = `https://api.github.com/repos/${REPO}/contents/${PATH}`;
  const cur = await fetch(url + "?ref=" + BRANCH, { headers: gh });
  if (!cur.ok && cur.status !== 404) return json({ error: "GitHub: " + cur.status + " " + (await cur.text()).slice(0, 200) }, 502);
  const file = cur.ok ? await cur.json() : null;
  const same = !!file && unb64(file.content || "") === content;
  const slugs = Object.keys(brands);

  if (new URL(req.url).searchParams.get("check") === "1") return json({ ok: true, check: true, brands: slugs, unchanged: same, github: cur.status });
  if (same) {
    await admin.from("tenants").update({ published_at: new Date().toISOString() }).in("slug", slugs.length ? slugs : ["-"]);
    return json({ ok: true, unchanged: true, brands: slugs });
  }
  const put = await fetch(url, {
    method: "PUT", headers: gh,
    body: JSON.stringify({ message: `Brand Studio: publish ${slugs.length} client brand${slugs.length === 1 ? "" : "s"}${slugs.length ? " (" + slugs.join(", ") + ")" : ""}`, content: b64(content), branch: BRANCH, ...(file ? { sha: file.sha } : {}) }),
  });
  const out = await put.json().catch(() => ({}));
  if (!put.ok) return json({ error: "GitHub: " + put.status + " " + JSON.stringify(out).slice(0, 200) }, 502);
  await admin.from("tenants").update({ published_at: new Date().toISOString() }).in("slug", slugs.length ? slugs : ["-"]);
  console.log("brand-publish", slugs.join(","), out?.commit?.sha);
  return json({ ok: true, brands: slugs, commit: out?.commit?.html_url, sha: out?.commit?.sha });
});
